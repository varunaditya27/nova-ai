"""Layer 5 orchestrator — emits the SocialIntelligencePacket (architecture doc §8).

Runs the coaching path: SC-4 detects an opportunity from the active patterns / recent
events / social graph, and (if all three gates pass) SC-5 injects it into the Layer 4
response. SC-1..SC-3 are background updaters whose outputs (the social graph, the events
detected this turn, the active patterns) are passed in here.

Hard rule (§11): Layer 5 NEVER blocks delivery of the Layer 4 response. If anything fails,
the ``FinalResponsePacket`` passes through unchanged (``modified_response = None``) and the
packet reflects that no coaching was injected.

The optional observation LLM (PATTERN_REFLECTION / CONFLICT_NAVIGATION text, §6.5) is
injected as ``observation_llm_fn`` so the layer runs offline.
"""

from __future__ import annotations

from datetime import datetime
from typing import Callable, Optional

from backend.layer3_reasoning.schemas import EmotionIntentPacket
from backend.layer4_persona.schemas import FinalResponsePacket
from backend.layer5_relationship import coaching_detector, coaching_modifier
from backend.layer5_relationship.schemas import (
    CoachingOpportunity,
    CoachingType,
    SocialContextUpdate,
    SocialEvent,
    SocialGraph,
    SocialIntelligencePacket,
    SocialPattern,
    SupportNetworkHealth,
    VoiceParameters,
)

# Coaching types whose observation text may be regenerated by an LLM (§6.5).
_LLM_OBSERVATION_TYPES = {
    CoachingType.PATTERN_REFLECTION.value,
    CoachingType.CONFLICT_NAVIGATION.value,
}


def _build_observation_prompt(opportunity: CoachingOpportunity, relationship_stage: str,
                              primary_emotion_label: str) -> str:
    pattern = opportunity.triggering_pattern
    desc = pattern.plain_language_description if pattern else opportunity.observation_text
    hook = pattern.coaching_hook if pattern else ""
    return (
        "Generate a 1-2 sentence observation that gently reflects a social pattern back to "
        "the user. Be warm, non-judgmental, non-prescriptive. Do not diagnose or tell them "
        "what to do. Frame as something you've noticed, not something you're certain about.\n\n"
        f"Pattern: {desc}\n"
        f"Coaching hook: {hook}\n"
        f"User's current emotional state: {primary_emotion_label}\n"
        f"Relationship stage: {relationship_stage}\n\n"
        "Generate observation (1-2 sentences maximum):"
    )


def build_social_context_update(
    social_graph: SocialGraph,
    active_patterns: list[SocialPattern],
    now: Optional[datetime] = None,
) -> SocialContextUpdate:
    """Compute the UWM social-context update written after the session (architecture doc §9)."""
    now = now or datetime.utcnow()
    nodes = list(social_graph.nodes.values())
    support_sources = [n for n in nodes if n.is_support_source]
    size = len(support_sources)
    if size >= 3:
        health = SupportNetworkHealth.ROBUST.value
    elif size == 2:
        health = SupportNetworkHealth.ADEQUATE.value
    elif size == 1:
        health = SupportNetworkHealth.THIN.value
    else:
        health = SupportNetworkHealth.ISOLATED.value

    active_conflicts = [
        {"person_id": n.person_id, "conflict_summary": ", ".join(n.conflict_topics),
         "intensity": n.conflict_count}
        for n in nodes if n.active_conflict
    ]
    return SocialContextUpdate(
        active_conflicts=active_conflicts,
        patterns_newly_detected=[p.pattern_id for p in active_patterns if not p.has_been_surfaced],
        support_network_size=size,
        support_network_health=health,
    )


def build_social_intelligence_packet(
    final_response: FinalResponsePacket,
    emotion_packet: EmotionIntentPacket,
    social_graph: Optional[SocialGraph] = None,
    event_history: Optional[list[SocialEvent]] = None,
    active_patterns: Optional[list[SocialPattern]] = None,
    events_detected: Optional[list[SocialEvent]] = None,
    relationship_stage: str = "developing",
    circadian_band: str = "afternoon",
    voice_parameters: Optional[VoiceParameters] = None,
    observation_llm_fn: Optional[Callable[[str], str]] = None,
    now: Optional[datetime] = None,
) -> SocialIntelligencePacket:
    """Run the Layer 5 coaching path and emit the SocialIntelligencePacket (§8, §11)."""
    now = now or datetime.utcnow()
    social_graph = social_graph or SocialGraph()
    active_patterns = active_patterns or []
    events_detected = events_detected or []
    voice_parameters = voice_parameters or VoiceParameters()

    packet = SocialIntelligencePacket(
        social_graph_updated=social_graph.version > 0,
        social_graph_version=social_graph.version,
        events_detected=events_detected,
        active_patterns=active_patterns,
        sc1_updated=social_graph.version > 0,
        sc2_events_found=len(events_detected),
        sc3_patterns_evaluated=len(active_patterns),
        sc3_patterns_active=len(active_patterns),
    )

    # The entire coaching path is best-effort: any failure → pass the L4 response through.
    try:
        opp = coaching_detector.detect_coaching_opportunity(
            active_patterns=active_patterns,
            recent_events=events_detected,
            social_graph=social_graph,
            conversation_mode=emotion_packet.conversation_mode,
            primary_emotion=emotion_packet.primary_emotion,
            background_state=emotion_packet.background_state,
            relationship_stage=relationship_stage,
            circadian_band=circadian_band,
            now=now,
        )
    except Exception:
        return packet  # §11: never block the Layer 4 response

    packet.coaching_opportunity = opp if opp.coaching_type else None
    packet.coaching_opportunity_detected = opp.opportunity_detected

    if opp.opportunity_detected:
        try:
            if observation_llm_fn and opp.coaching_type in _LLM_OBSERVATION_TYPES:
                prompt = _build_observation_prompt(
                    opp, relationship_stage, emotion_packet.primary_emotion.primary_label
                )
                regenerated = (observation_llm_fn(prompt) or "").strip()
                if regenerated:
                    opp.observation_text = regenerated
            modified = coaching_modifier.inject_observation(final_response, opp, voice_parameters)
        except Exception:
            return packet  # §11: never block on injection failure

        if modified.social_coaching_injected:
            packet.coaching_injected = True
            packet.modified_response = modified
        else:
            # Headroom guard flipped it to deferred → queue for Layer 6.
            packet.coaching_deferred = True
            packet.proactive_coaching_queue = [opp]
    elif opp.coaching_type is not None:
        # Available but timing/recency deferred → queue for Layer 6.
        packet.coaching_deferred = True
        packet.proactive_coaching_queue = [opp]

    packet.social_context_update = build_social_context_update(social_graph, active_patterns, now)
    return packet
