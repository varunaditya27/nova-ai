"""SC-4 coaching-opportunity builders + observation templates (architecture doc §6.4–6.5).

Split out of ``coaching_detector.py``: constructing an opportunity object from a
pattern/event/support-gap, distinct from the three-gate timing model.
"""

from __future__ import annotations

from backend.layer5_relationship.schemas import (
    CoachingOpportunity,
    CoachingType,
    DeliveryMode,
    SocialEvent,
    SocialGraph,
    SocialPattern,
    SocialPatternType,
    Urgency,
)

# Pattern type → coaching type (architecture doc §6.2).
PATTERN_TO_COACHING = {
    SocialPatternType.RECURRING_CONFLICT_TOPIC.value: CoachingType.PATTERN_REFLECTION.value,
    SocialPatternType.RECURRING_SUPPORT_FAILURE.value: CoachingType.PATTERN_REFLECTION.value,
    SocialPatternType.CONFLICT_AVOIDANCE_PATTERN.value: CoachingType.PATTERN_REFLECTION.value,
    SocialPatternType.PEOPLE_PLEASING_PATTERN.value: CoachingType.PATTERN_REFLECTION.value,
    SocialPatternType.BOUNDARY_DIFFICULTY_PATTERN.value: CoachingType.BOUNDARY_SUPPORT.value,
    SocialPatternType.SOCIAL_WITHDRAWAL_PATTERN.value: CoachingType.SUPPORT_NETWORK_NUDGE.value,
    SocialPatternType.SUPPORT_NETWORK_EROSION.value: CoachingType.SUPPORT_NETWORK_NUDGE.value,
    SocialPatternType.HEALTHY_RELATIONSHIP_PATTERN.value: CoachingType.STRENGTH_ACKNOWLEDGMENT.value,
    SocialPatternType.RECURRING_POSITIVE_REINFORCEMENT.value: CoachingType.STRENGTH_ACKNOWLEDGMENT.value,
}

# Template observations (architecture doc §6.5). PATTERN_REFLECTION / CONFLICT_NAVIGATION
# are generated by the orchestrator's LLM; the rest are filled here.
OBSERVATION_TEMPLATES = {
    CoachingType.RELATIONSHIP_CHECK_IN: [
        "You haven't mentioned {name} in a while — how are things there?",
        "I realized I haven't heard about {name} lately. Is everything okay between you two?",
    ],
    CoachingType.SUPPORT_NETWORK_NUDGE: [
        "I've noticed you've been carrying a lot lately — have you been able to lean on anyone?",
        "Is there someone in your life you've been able to talk to about all of this?",
    ],
    CoachingType.STRENGTH_ACKNOWLEDGMENT: [
        "I want to name something — the way you handled that showed real maturity.",
        "That boundary you set with {name} — that took courage. Seriously.",
    ],
    CoachingType.BOUNDARY_SUPPORT: [
        "Setting that limit with {name} sounds like exactly the right call. "
        "It's okay that it's uncomfortable.",
        "The fact that it feels hard to hold that boundary doesn't mean you're wrong to have it.",
    ],
}


def build_opportunity_from_pattern(
    pattern: SocialPattern, display_name: str = ""
) -> CoachingOpportunity:
    """Build a coaching opportunity from an active pattern (architecture doc §6.4–6.5)."""
    coaching_type = PATTERN_TO_COACHING.get(
        pattern.pattern_type, CoachingType.PATTERN_REFLECTION.value
    )
    person_id = pattern.person_ids_involved[0] if pattern.person_ids_involved else None
    is_reflection = coaching_type == CoachingType.PATTERN_REFLECTION.value

    if is_reflection:
        # Provisional framing (§7.4): noticed, not concluded; invites confirmation.
        observation = (
            f"I've noticed something I wanted to mention — {pattern.plain_language_description} "
            "Does that feel accurate to you?"
        )
        framing = "I've noticed a pattern that I wanted to mention"
        delivery = DeliveryMode.AS_QUESTION.value
    else:
        template = OBSERVATION_TEMPLATES.get(CoachingType(coaching_type), [""])[0]
        observation = template.format(name=display_name or "them")
        framing = "Something I've been thinking about"
        delivery = DeliveryMode.INLINE.value

    urgency = Urgency.MEDIUM.value if pattern.pattern_strength >= 0.6 else Urgency.LOW.value
    return CoachingOpportunity(
        opportunity_detected=True,
        coaching_type=coaching_type,
        triggering_pattern=pattern,
        triggering_person=person_id,
        delivery_mode=delivery,
        urgency=urgency,
        observation_text=observation,
        observation_framing=framing,
        requires_explicit_consent=is_reflection,
    )


def build_opportunity_from_conflict(
    event: SocialEvent, social_graph: SocialGraph
) -> CoachingOpportunity:
    """Build a conflict-navigation opportunity from an active conflict (§6.4 Priority 2)."""
    node = social_graph.nodes.get(event.person_id)
    name = node.display_name if node else "them"
    return CoachingOpportunity(
        opportunity_detected=True,
        coaching_type=CoachingType.CONFLICT_NAVIGATION.value,
        triggering_event=event,
        triggering_person=event.person_id,
        delivery_mode=DeliveryMode.AS_QUESTION.value,
        urgency=Urgency.MEDIUM.value,
        observation_text=(
            f"This thing with {name} sounds like it's weighing on you. "
            "Do you want to talk through it, or just have it heard?"
        ),
        observation_framing="Checking in on the conflict",
    )


def build_support_network_nudge(support_sources: list) -> CoachingOpportunity:
    """Build a support-network nudge (architecture doc §6.4 Priority 3)."""
    return CoachingOpportunity(
        opportunity_detected=True,
        coaching_type=CoachingType.SUPPORT_NETWORK_NUDGE.value,
        delivery_mode=DeliveryMode.INLINE.value,
        urgency=Urgency.LOW.value,
        observation_text=OBSERVATION_TEMPLATES[CoachingType.SUPPORT_NETWORK_NUDGE][0],
        observation_framing="A gentle nudge",
    )
